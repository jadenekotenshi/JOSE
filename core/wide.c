#include "wide.h"

typedef struct { unsigned long lo, hi; } Range;

static const Range ZERO[] = {
    { 0x0300, 0x036F }, { 0x0483, 0x0489 }, { 0x0591, 0x05BD }, { 0x05BF, 0x05BF }, { 0x05C1, 0x05C2 }, { 0x05C4, 0x05C5 }, { 0x05C7, 0x05C7 },
    { 0x0610, 0x061A }, { 0x064B, 0x065F }, { 0x0670, 0x0670 }, { 0x06D6, 0x06DC }, { 0x06DF, 0x06E4 }, { 0x06E7, 0x06E8 }, { 0x06EA, 0x06ED },
    { 0x0E31, 0x0E31 }, { 0x0E34, 0x0E3A }, { 0x0E47, 0x0E4E }, { 0x1AB0, 0x1AFF }, { 0x1DC0, 0x1DFF }, { 0x200B, 0x200F }, { 0x202A, 0x202E },
    { 0x2060, 0x2064 }, { 0x20D0, 0x20FF }, { 0xFE00, 0xFE0F }, { 0xFE20, 0xFE2F }, { 0xFEFF, 0xFEFF }, { 0xE0100, 0xE01EF }
};

static const Range WIDE[] = {
    { 0x1100, 0x115F }, { 0x2E80, 0x303E }, { 0x3041, 0x33FF }, { 0x3400, 0x4DBF }, { 0x4E00, 0x9FFF }, { 0xA000, 0xA4CF }, { 0xA960, 0xA97F },
    { 0xAC00, 0xD7A3 }, { 0xF900, 0xFAFF }, { 0xFE10, 0xFE19 }, { 0xFE30, 0xFE6F }, { 0xFF00, 0xFF60 }, { 0xFFE0, 0xFFE6 },
    { 0x1F300, 0x1F64F }, { 0x1F900, 0x1F9FF }, { 0x20000, 0x2FFFD }, { 0x30000, 0x3FFFD }
};

static int in(const Range *r, unsigned n, unsigned long cp)
{
    unsigned i;

    for (i = 0; i < n; i++) if (cp >= r[i].lo && cp <= r[i].hi) return 1;
    return 0;
}

int wide_cp(unsigned long cp)
{
    if (cp < 0x300) return 1;
    if (in(ZERO, sizeof ZERO / sizeof ZERO[0], cp)) return 0;
    if (in(WIDE, sizeof WIDE / sizeof WIDE[0], cp)) return 2;
    return 1;
}

int wide_unit(unsigned c)
{
    if (c >= 0xD800 && c <= 0xDBFF) return 2;           /* the pair is wide (emoji, CJK Ext. B) or at worst takes two cells */
    if (c >= 0xDC00 && c <= 0xDFFF) return 0;
    return wide_cp(c);
}
