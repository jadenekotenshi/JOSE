#!/usr/bin/env python3
"""Writes core/enc_tables.c: the conversion tables of the legacy encodings that core/enc.c reads and writes, made from Python's own codecs.

Single-byte tables hold the 128 characters of bytes 0x80..0xFF (0xFFFF where the byte is undefined).  Double-byte tables are indexed by
(lead - lead_lo) * (trail_hi - trail_lo + 1) + (trail - trail_lo) and hold the Unicode character (0 where the pair is not assigned).
Run from the top of the tree:  python3 tools/gen_enc_tables.py   and commit the result."""
import re

SINGLE = [  # (C name, Python codec)
    ("ISO8859_2", "iso8859_2"), ("ISO8859_5", "iso8859_5"), ("ISO8859_7", "iso8859_7"), ("ISO8859_9", "iso8859_9"),
    ("ISO8859_15", "iso8859_15"), ("CP1250", "cp1250"), ("CP1251", "cp1251"), ("CP1252", "cp1252"),
    ("KOI8R", "koi8_r"), ("MACROMAN", "mac_roman"),
]
# (C name, codec, lead lo, lead hi, trail lo, trail hi)
DOUBLE = [
    ("CP932", "cp932", 0x81, 0xFC, 0x40, 0xFC),
    ("JIS0208", "euc_jp", 0xA1, 0xFE, 0xA1, 0xFE),
    ("GBK", "gbk", 0x81, 0xFE, 0x40, 0xFE),
    ("CP950", "cp950", 0x81, 0xFE, 0x40, 0xFE),
    ("CP949", "cp949", 0x81, 0xFE, 0x41, 0xFE),
]


def one_unichar(s):
    return ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0


def single_table(codec):
    out = []
    for b in range(0x80, 0x100):
        try:
            c = bytes([b]).decode(codec)
            out.append(ord(c) if len(c) == 1 else 0xFFFF)
        except UnicodeDecodeError:
            out.append(0xFFFF)
    return out


def double_table(codec, llo, lhi, tlo, thi):
    out = []
    for lead in range(llo, lhi + 1):
        for trail in range(tlo, thi + 1):
            try:
                c = bytes([lead, trail]).decode(codec)
                out.append(one_unichar(c))
            except UnicodeDecodeError:
                out.append(0)
    return out


def jis0212():
    out = []
    for lead in range(0xA1, 0xFF):
        for trail in range(0xA1, 0xFF):
            try:
                c = bytes([0x8F, lead, trail]).decode("euc_jp")
                out.append(one_unichar(c))
            except UnicodeDecodeError:
                out.append(0)
    return out


def emit(name, vals, per_line=12):
    s = "static const u16 %s[%d] = {\n" % (name, len(vals))
    for i in range(0, len(vals), per_line):
        s += "    " + ",".join("0x%04x" % v for v in vals[i:i + per_line]) + (",\n" if i + per_line < len(vals) else "\n")
    return s + "};\n\n"


def main():
    o = ["/* GENERATED by tools/gen_enc_tables.py from Python's codecs -- do not edit */\n",
         '#include "enc_tables.h"\n\n']
    for cname, codec in SINGLE:
        o.append(emit("sb_%s" % cname, single_table(codec)))
    # the high bytes of the double-byte encodings (half-width katakana and the like)
    for cname, codec in (("CP932", "cp932"), ("EUCJP", "euc_jp"), ("GBK", "gbk"), ("CP950", "cp950"), ("CP949", "cp949")):
        o.append(emit("hi_%s" % cname, single_table(codec)))
    for cname, codec, llo, lhi, tlo, thi in DOUBLE:
        o.append(emit("db_%s" % cname, double_table(codec, llo, lhi, tlo, thi)))
    o.append(emit("db_JIS0212", jis0212()))
    o.append("const EncSingle enc_single[ENC_N_SINGLE] = {\n" + "".join("    { sb_%s },\n" % c for c, _ in SINGLE) + "};\n\n")
    o.append("const EncHigh enc_high_cp932 = { hi_CP932 };\nconst EncHigh enc_high_eucjp = { hi_EUCJP };\nconst EncHigh enc_high_gbk = { hi_GBK };\n"
             "const EncHigh enc_high_cp950 = { hi_CP950 };\nconst EncHigh enc_high_cp949 = { hi_CP949 };\n\n")
    for cname, codec, llo, lhi, tlo, thi in DOUBLE:
        o.append("const EncDouble enc_db_%s = { %d, %d, %d, %d, db_%s };\n" % (cname.lower(), llo, lhi, tlo, thi, cname))
    o.append("const EncDouble enc_db_jis0212 = { 0xA1, 0xFE, 0xA1, 0xFE, db_JIS0212 };\n")
    open("core/enc_tables.c", "w").write("".join(o))
    print("wrote core/enc_tables.c")


main()
