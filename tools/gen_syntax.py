imake_dirs = "include define undef if ifdef ifndef else elif endif error pragma line".split()
imake_kw = [keyword("<%s>" % w, BUILTIN) for w in imake_macros] + [keyword("\\$[@<*%?]", VARIABLE)]
hdr = "\\<[abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_./0123456789]"
write("Imakefile", file_text("Imakefile and Imake templates (cpp lines, XCOMM comments, make rules)", imake_kw,
      [context('"', '"', STRING),
       context("\\$\\(", "\\)", VARIABLE, bold=True, comment="$(VAR)"),
       context("\\$\\{", "\\}", VARIABLE, bold=True, comment="${VAR}"),
       context("^#", "\n", DIRECTIVE, bold=True, skips=("\\\\\n",), comment="cpp line", keywords=[]),
       context("^XCOMM", "\n", COMMENT, italic=True, comment="XCOMM: a comment that cpp leaves in the Makefile"),
       context("/\\*", "\\*/", COMMENT, italic=True),
       context(hdr, "\\>", "0.55 0.2 0.55", parent=4, comment="<header> in a cpp line"),
       context('"', '"', "0.55 0.2 0.55", parent=4, comment='"header" in a cpp line')]))

# ---- the macro language ----
macro_verbs = "insert action command find replace replace-all replace-sel filter exec".split()
write("PilcrowMacro", file_text("Pilcrow macros", [keyword("^%s>" % w, KEYWORD) for w in macro_verbs],
      [context('"', '"', STRING, skips=ESC),
       context("#", "\n", COMMENT, italic=True)]))

# ---- Markdown: headings, quotes, fenced code, HTML comments (everything else is plain text) ----
write("Markdown", file_text("Markdown", [],
      [context("```", "```", STRING),
       context("~~~", "~~~", STRING),
       context("^#", "\n", "0.1 0.3 0.8", bold=True),
       context("^\\>", "\n", COMMENT, italic=True),
       context("\\<!--", "--\\>", COMMENT, italic=True)]))


# ---- character sets (HighlighterKit's [...] holds the characters themselves: there are no ranges) ----
LOW = "abcdefghijklmnopqrstuvwxyz"
UP = LOW.upper()
DIG = "0123456789"
HEXC = "0123456789abcdefABCDEF"


def setof(chars):
    return "[" + "".join(("\\" + c) if c in "]\\" else c for c in chars) + "]"


ID = LOW + UP + DIG + "_"
IDS = setof(ID)
STR_END = '[\\"\n]'                                 # a string ends at its closing quote or at the end of the line


def line_string(quote, color=STRING, skips=None, parent=None, comment=None):
    return context(quote, setof(quote + "\n"), color, skips=skips if skips is not None else (ESC if quote == '"' else ESC1), parent=parent, comment=comment)


# ---- INI ----
ini_key = "^" + setof(ID + ".-") + setof(ID + ".-") + "*"
write("INI", file_text("INI files (sections, keys, ; and # comments)",
      [keyword(ini_key, BUILTIN, False), keyword("<0x[0123456789abcdefABCDEF]*>", NUMBER, False), NUM] +
      words(["true", "false", "yes", "no", "on", "off"], KEYWORD, False),
      [context("^\\[", "\n", DIRECTIVE, bold=True, comment="[section]"),
       context("^;", "\n", COMMENT, italic=True),
       context("^#", "\n", COMMENT, italic=True),
       line_string('"')]))

# ---- CSS ----
