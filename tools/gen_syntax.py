js_builtin = "console document window Object Array String Number Boolean Math JSON Date RegExp Error Promise Map Set Symbol require module exports process".split()
write("JavaScript", file_text("JavaScript", words(js_kw, KEYWORD) + words(js_lit, BUILTIN) + words(js_builtin, BUILTIN, False) + [HEX, NUM],
      [context('"', '"', STRING, skips=ESC),
       context("'", "'", STRING, skips=ESC1),
       context("`", "`", STRING, skips=("\\\\\\\\", "\\\\`"), comment="template literal"),
       context("\\$\\{", "\\}", VARIABLE, bold=True, parent=3, comment="${...} inside a template literal"),
       context("/\\*", "\\*/", COMMENT, italic=True),
       context("//", "\n", COMMENT, italic=True)]))

# ---- Ruby ----
rb_kw = """alias and begin break case class def do else elsif end ensure false for if in module next nil not or redo rescue retry
return self super then true undef unless until when while yield __FILE__ __LINE__ BEGIN END""".split()
rb_builtin = """require require_relative load include extend prepend attr_accessor attr_reader attr_writer private public protected
module_function lambda proc puts print p raise loop catch throw block_given freeze new initialize""".split()
write("Ruby", file_text("Ruby", words(rb_kw, KEYWORD) + words(rb_builtin, BUILTIN, False) + [keyword("@@?[A-Za-z_][A-Za-z0-9_]*", VARIABLE, False),
                                                    keyword(":[A-Za-z_][A-Za-z0-9_]*", NUMBER, False), NUM],
      [context('"', '"', STRING, skips=ESC),
       context("'", "'", STRING, skips=ESC1),
       context("\\#\\{", "\\}", VARIABLE, bold=True, parent=1, comment="#{...} inside a double-quoted string"),
       context("^=begin", "^=end", COMMENT, italic=True),
       context("#", "\n", COMMENT, italic=True)]))

# ---- BSD make ----
