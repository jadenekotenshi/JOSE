#!/usr/bin/env python3
"""Writes the HighlighterKit .syntax files for JSON, JavaScript, Ruby, Zsh, BSD make and Imake.

The files are long because every keyword is a dictionary of its own; this script keeps their source short.  Run it from the
top of the tree (python3 tools/gen_syntax.py) and commit the result.  Colours are the same as in the other modes."""

import os, re

KEYWORD = "0.6 0.45 0.75"
BUILTIN = "0.2 0.3 0.8"
NUMBER = "0.8 0.4 0"
STRING = "0 0.7 0"
COMMENT = "0 0.5 0"
VARIABLE = "0.1 0.3 0.8"
DIRECTIVE = "0.8 0 0"


def q(s):
    """A pattern as it is written in a property list (backslashes and quotes doubled up)."""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def keyword(pattern, color, bold=True, italic=False):
    out = '        {\n          Pattern = "%s";\n          ForegroundColor = "%s";\n' % (q(pattern), color)
    if bold:
        out += "          Bold = YES;\n"
    if italic:
        out += "          Italic = YES;\n"
    return out + "        }"


def words(list_, color, bold=True):
    return [keyword("<%s>" % w, color, bold) for w in list_]


def context(begin, end, color, skips=(), italic=False, bold=False, keywords=(), parent=None, comment=None):
    out = "    {\n"
    if comment:
        out = "    /* %s */\n    {\n" % comment
    if parent is not None:
        out += "      Parent = %d;\n" % parent
    out += '      Beginning = "%s";\n      Ending = "%s";\n' % (q(begin), q(end))
    if skips:
        out += "      ContextSkips = (\n" + ",\n".join('        "%s"' % q(s) for s in skips) + "\n      );\n"
    out += '      ForegroundColor = "%s";\n' % color
    if italic:
        out += "      Italic = YES;\n"
    if bold:
        out += "      Bold = YES;\n"
    if keywords:
        out += "      Keywords = (\n" + ",\n".join(keywords) + "\n      );\n"
    return out + "    }"


def file_text(title, default_keywords, contexts):
    out = "/*\n * Highlighting rules for %s.\n * Generated by tools/gen_syntax.py: change that, not this.\n */\n{\n  Contexts = (\n    {\n" % title
    out += "      Keywords = (\n" + ",\n".join(default_keywords) + "\n      );\n    }"
    for c in contexts:
        out += ",\n\n" + c
    return out + "\n  );\n}\n"


def write(name, text):
    with open(os.path.join("syntax", name + ".syntax"), "w") as f:
        f.write(text)
    print("wrote syntax/%s.syntax" % name)


# Skips for a string: a pair of backslashes, and a backslash and the quote (HighlighterKit's own pattern syntax: \\ is one backslash).
ESC = ("\\\\\\\\", '\\\\"')
ESC1 = ("\\\\\\\\", "\\\\'")
NUM = keyword("<[0-9][0-9]*>", NUMBER, False)
HEX = keyword("<0x[0-9A-Fa-f]*>", NUMBER, False)

# ---- JSON ----
write("JSON", file_text("JSON", words(["true", "false", "null"], KEYWORD) + [HEX, NUM],
      [context('"', '"', STRING, skips=ESC)]))

# ---- JavaScript ----
js_kw = """break case catch class const continue debugger default delete do else export extends finally for function if import
in instanceof let new of return super switch this throw try typeof var void while with yield async await static get set""".split()
js_lit = "true false null undefined NaN Infinity".split()
js_builtin = "console document window Object Array String Number Boolean Math JSON Date RegExp Error Promise Map Set Symbol require module exports process".split()
write("JavaScript", file_text("JavaScript", words(js_kw, KEYWORD) + words(js_lit, BUILTIN) + words(js_builtin, BUILTIN, False) + [HEX, NUM],
      [context('"', '"', STRING, skips=ESC),
       context("'", "'", STRING, skips=ESC1),
       context("`", "`", STRING, skips=("\\\\\\\\", "\\\\`"), comment="template literal"),
       context("\\$\\{", "\\}", VARIABLE, bold=True, parent=3, comment="${...} inside a template literal"),
       context("/\\*", "\\*/", COMMENT, italic=True),
       context("//", "\n", COMMENT, italic=True)]))

# ---- Ruby ----
rb_kw = """alias and begin break case class def do else elsif end ensure false for if in module next nil not or redo rescue retry
return self super then true undef unless until when while yield __FILE__ __LINE__ BEGIN END""".split()
rb_builtin = """require require_relative load include extend prepend attr_accessor attr_reader attr_writer private public protected
module_function lambda proc puts print p raise loop catch throw block_given freeze new initialize""".split()
write("Ruby", file_text("Ruby", words(rb_kw, KEYWORD) + words(rb_builtin, BUILTIN, False) + [keyword("@@?[A-Za-z_][A-Za-z0-9_]*", VARIABLE, False),
                                                    keyword(":[A-Za-z_][A-Za-z0-9_]*", NUMBER, False), NUM],
      [context('"', '"', STRING, skips=ESC),
       context("'", "'", STRING, skips=ESC1),
       context("\\#\\{", "\\}", VARIABLE, bold=True, parent=1, comment="#{...} inside a double-quoted string"),
       context("^=begin", "^=end", COMMENT, italic=True),
       context("#", "\n", COMMENT, italic=True)]))

# ---- BSD make ----
bsd_dir = """include sinclude include_next if ifdef ifndef ifmake ifnmake else elif elifdef elifndef endif for endfor undef error warning info
export export-env export-literal unexport unexport-env poison dinclude""".split()
bsd_targets = """PHONY SUFFIXES DEFAULT PATH WAIT MAIN SILENT IGNORE PRECIOUS MAKEFLAGS NOTPARALLEL NOPATH NOMETA NOMETA_CMP USE USEBEFORE
EXEC INVISIBLE JOIN MADE MAKE MFLAGS NOTMAIN OPTIONAL ORDER STALE""".split()
bsd_kw = [keyword("^\\.[ ]*%s>" % w, DIRECTIVE) for w in bsd_dir] + [keyword("^\\.%s>" % w, KEYWORD) for w in bsd_targets]
bsd_kw += [keyword("\\$[@<*%?>]", VARIABLE), keyword("^[A-Za-z_][A-Za-z0-9_.]*[ ]*[?:+!]?=", BUILTIN)]
write("BSDMakefile", file_text("BSD make files (BSDmakefile, bsd.*.mk)", bsd_kw,
      [context('"', '"', STRING),
       context("\\$\\{", "\\}", VARIABLE, bold=True, comment="${VAR}"),
       context("\\$\\(", "\\)", VARIABLE, bold=True, comment="$(VAR)"),
       context("#", "\n", COMMENT, italic=True, skips=("\\\\\n",))]))

# ---- Imake ----
imake_macros = """AllTarget NormalProgramTarget NormalLibraryTarget NormalSharedLibraryTarget NormalLintTarget InstallProgram InstallManPage
InstallMultiple InstallNonExecFile InstallLibrary InstallScript InstallAppDefaults DependTarget CleanTarget SubdirTarget
MakeSubdirs MakeMakeSubdirs DependSubdirs InstallSubdirs LinkSourceFile ObjectCompile CCsource SRCS OBJS HEADERS LOCAL_LIBRARIES
SYS_LIBRARIES DEPLIBS EXTRA_LIBRARIES EXTRA_INCLUDES EXTRA_DEFINES DEFINES INCLUDES LDOPTIONS SUBDIRS XCOMM NullParameter""".split()
imake_dirs = "include define undef if ifdef ifndef else elif endif error pragma line".split()
imake_kw = [keyword("<%s>" % w, BUILTIN) for w in imake_macros] + [keyword("\\$[@<*%?]", VARIABLE)]
hdr = "\\<[abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_./0123456789]"
write("Imakefile", file_text("Imakefile and Imake templates (cpp lines, XCOMM comments, make rules)", imake_kw,
      [context('"', '"', STRING),
       context("\\$\\(", "\\)", VARIABLE, bold=True, comment="$(VAR)"),
       context("\\$\\{", "\\}", VARIABLE, bold=True, comment="${VAR}"),
       context("^#", "\n", DIRECTIVE, bold=True, skips=("\\\\\n",), comment="cpp line", keywords=[]),
       context("^XCOMM", "\n", COMMENT, italic=True, comment="XCOMM: a comment that cpp leaves in the Makefile"),
       context("/\\*", "\\*/", COMMENT, italic=True),
       context(hdr, "\\>", "0.55 0.2 0.55", parent=4, comment="<header> in a cpp line"),
       context('"', '"', "0.55 0.2 0.55", parent=4, comment='"header" in a cpp line')]))

# ---- the macro language ----
macro_verbs = "insert action command find replace replace-all replace-sel filter exec".split()
write("JOSEMacro", file_text("JOSE macros", [keyword("^%s>" % w, KEYWORD) for w in macro_verbs],
      [context('"', '"', STRING, skips=ESC),
       context("#", "\n", COMMENT, italic=True)]))

# ---- Markdown: headings, quotes, fenced code, HTML comments (everything else is plain text) ----
write("Markdown", file_text("Markdown", [],
      [context("```", "```", STRING),
       context("~~~", "~~~", STRING),
       context("^#", "\n", "0.1 0.3 0.8", bold=True),
       context("^\\>", "\n", COMMENT, italic=True),
       context("\\<!--", "--\\>", COMMENT, italic=True)]))

# ---- Zsh: the Shell rules and the words that zsh adds ----
extra = """autoload bindkey builtin bye cdr chdir compdef compinit declare disown emulate fc float functions getopts hash history integer
jobs kill limit local nocorrect noglob popd print pushd rehash repeat setopt shopt sched stat typeset unfunction unhash unlimit
unsetopt vared whence where which zcompile zformat zle zmodload zparseopts zstyle zsh coproc foreach end""".split()
src = open("syntax/Shell.syntax").read()
if "Generated by tools/gen_syntax.py" in src:
    raise SystemExit("syntax/Shell.syntax was overwritten")
extra_kw = ",\n".join(keyword("<%s>" % w, BUILTIN, False) for w in extra)
src = src.replace("Highlighting rules for sh, ksh and bash scripts.", "Highlighting rules for zsh: the sh/ksh/bash rules and the words that zsh adds.\n * Generated by tools/gen_syntax.py from Shell.syntax: change those, not this", 1)
src = src.replace("      Keywords = (\n", "      Keywords = (\n" + extra_kw + ",\n", 1)
write("Zsh", src)
