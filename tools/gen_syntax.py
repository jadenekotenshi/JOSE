#!/usr/bin/env python3
"""Writes the HighlighterKit .syntax files for JSON, JavaScript, Ruby, Zsh, BSD make and Imake.

The files are long because every keyword is a dictionary of its own; this script keeps their source short.  Run it from the
top of the tree (python3 tools/gen_syntax.py) and commit the result.  Colours are the same as in the other modes."""

import os, re

KEYWORD = "0.6 0.45 0.75"
BUILTIN = "0.2 0.3 0.8"
NUMBER = "0.8 0.4 0"
STRING = "0 0.7 0"
COMMENT = "0 0.5 0"
VARIABLE = "0.1 0.3 0.8"
DIRECTIVE = "0.8 0 0"


def q(s):
    """A pattern as it is written in a property list (backslashes and quotes doubled up)."""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def keyword(pattern, color, bold=True, italic=False):
    out = '        {\n          Pattern = "%s";\n          ForegroundColor = "%s";\n' % (q(pattern), color)
    if bold:
        out += "          Bold = YES;\n"
    if italic:
        out += "          Italic = YES;\n"
    return out + "        }"


def words(list_, color, bold=True):
    return [keyword("<%s>" % w, color, bold) for w in list_]


def context(begin, end, color, skips=(), italic=False, bold=False, keywords=(), parent=None, comment=None):
    out = "    {\n"
    if comment:
        out = "    /* %s */\n    {\n" % comment
    if parent is not None:
        out += "      Parent = %d;\n" % parent
    out += '      Beginning = "%s";\n      Ending = "%s";\n' % (q(begin), q(end))
    if skips:
        out += "      ContextSkips = (\n" + ",\n".join('        "%s"' % q(s) for s in skips) + "\n      );\n"
    out += '      ForegroundColor = "%s";\n' % color
    if italic:
        out += "      Italic = YES;\n"
    if bold:
        out += "      Bold = YES;\n"
    if keywords:
        out += "      Keywords = (\n" + ",\n".join(keywords) + "\n      );\n"
    return out + "    }"


def file_text(title, default_keywords, contexts):
    out = "/*\n * Highlighting rules for %s.\n * Generated by tools/gen_syntax.py: change that, not this.\n */\n{\n  Contexts = (\n    {\n" % title
    out += "      Keywords = (\n" + ",\n".join(default_keywords) + "\n      );\n    }"
    for c in contexts:
        out += ",\n\n" + c
    return out + "\n  );\n}\n"


def write(name, text):
    with open(os.path.join("syntax", name + ".syntax"), "w") as f:
        f.write(text)
    print("wrote syntax/%s.syntax" % name)


# Skips for a string: a pair of backslashes, and a backslash and the quote (HighlighterKit's own pattern syntax: \\ is one backslash).
ESC = ("\\\\\\\\", '\\\\"')
ESC1 = ("\\\\\\\\", "\\\\'")
NUM = keyword("<[0-9][0-9]*>", NUMBER, False)
HEX = keyword("<0x[0-9A-Fa-f]*>", NUMBER, False)

# ---- JSON ----
write("JSON", file_text("JSON", words(["true", "false", "null"], KEYWORD) + [HEX, NUM],
      [context('"', '"', STRING, skips=ESC)]))

# ---- JavaScript ----
js_kw = """break case catch class const continue debugger default delete do else export extends finally for function if import
in instanceof let new of return super switch this throw try typeof var void while with yield async await static get set""".split()
